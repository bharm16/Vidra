import { test, expect } from "@playwright/test";
import { authenticated, drafts, guard, keepWords, makePicture, project, projectId, versions } from "./helpers";

test.beforeEach(async ({ page }) => { await authenticated(page); });
test("explicit project creation owns the first-visit pose without replaying it onto another working copy", async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto("/app");
  const name = `First visit ${crypto.randomUUID()}`;
  await page.getByRole("button", { name: "New project", exact: true }).first().click();
  await page.getByLabel("Project name", { exact: true }).fill(name);
  await page.getByRole("button", { name: "Create project", exact: true }).click();
  const workspace = page.locator(".vf-workspace"), composer = page.locator(".vf-composer");
  await expect(workspace).toHaveAttribute("data-workspace-entry", "created");
  await page.evaluate(() => document.fonts.ready);
  await expect.poll(() => composer.boundingBox()).toEqual({ x: 27, y: 270, width: 336, height: 232 });
  await expect(page.getByLabel("Current request words", { exact: true })).toHaveValue("");
  const id = projectId(page), initial = (await drafts(page, id))[0]!;
  expect(await drafts(page, id)).toHaveLength(1);
  await page.screenshot({ path: testInfo.outputPath("N38-created-native-app.png") });
  await keepWords(page, "Keep this new project draft");
  await expect(workspace).toHaveAttribute("data-workspace-entry", "created");
  expect((await drafts(page, id))[0]?.id).toBe(initial.id);
  await page.setViewportSize({ width: 1440, height: 900 });
  await expect.poll(async () => (await composer.boundingBox())?.width).toBe(720);
  await page.getByRole("button", { name: "New request", exact: true }).click();
  await expect(page.getByLabel("Current request words", { exact: true })).toHaveValue("");
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(workspace).not.toHaveAttribute("data-workspace-entry");
  await expect.poll(() => composer.boundingBox()).toEqual({ x: 27, y: 282, width: 336, height: 232 });
  await expect.poll(async () => (await drafts(page, id)).length).toBe(2);
  expect((await drafts(page, id)).find(draft => draft.id === initial.id)).toMatchObject({ status: "parked", instructions: "Keep this new project draft" });
  await page.reload();
  await expect(page.getByLabel("Current request words", { exact: true })).toHaveValue("");
  await expect(workspace).not.toHaveAttribute("data-workspace-entry");
  await expect.poll(() => composer.boundingBox()).toEqual({ x: 27, y: 282, width: 336, height: 232 });
  await page.goto("/app");
  await page.getByRole("button", { name: `Open project ${name}`, exact: true }).click();
  await expect(workspace).toHaveAttribute("data-workspace-entry", "reopen");
  await expect.poll(() => composer.boundingBox()).toEqual({ x: 27, y: 282, width: 336, height: 232 });
  expect(await drafts(page, id)).toHaveLength(2);
  await guard(page);
});

test("saved words survive reload, chip selection and direct Make produces owned reloadable media", async ({ page }) => {
  await project(page);
  const words = "A runner passes through warm stadium lights. Keep the current work.";
  await keepWords(page, words);
  const url = page.url();
  await page.reload();
  await expect(page.getByLabel("Current request words", { exact: true })).toHaveValue(words);
  await page.getByRole("button", { name: "Shape: 16:9", exact: true }).click();
  await page.getByRole("button", { name: "1:1", exact: true }).click();
  await expect(page.getByRole("button", { name: "Shape: 1:1", exact: true })).toBeVisible();
  await expect(page.getByLabel("Current request words", { exact: true })).toHaveValue(words);
  await makePicture(page, words);
  await expect(page.getByRole("button", { name: `View ${words}`, exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole("button", { name: `View ${words}`, exact: true })).toBeVisible();
  expect(await versions(page)).toHaveLength(1);
  await expect(page).toHaveURL(url);
  await guard(page);
});
test("a failed history load is actionable and does not erase a retained draft", async ({ page }) => {
  await project(page);
  await keepWords(page, "Retain this before observing older work");
  await page.route("**/conversations/*/requests", route => route.fulfill({ status: 503, json: { success: false, error: "History is unavailable" } }));
  await page.reload();
  await expect(page.getByText(/History could not load/)).toBeVisible();
  await expect(page.getByLabel("Current request words", { exact: true })).toHaveValue("Retain this before observing older work");
  await guard(page);
});
test("at 320px request and media pane controls remain reachable without losing words", async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 720 });
  await project(page);
  await keepWords(page, "Words retained on a narrow screen");
  await page.getByRole("button", { name: "Project media", exact: true }).last().click();
  await page.getByRole("button", { name: "Request", exact: true }).click();
  await expect(page.getByLabel("Current request words", { exact: true })).toHaveValue("Words retained on a narrow screen");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await guard(page);
});
