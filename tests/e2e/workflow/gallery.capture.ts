/** Opt-in after functional QA: WORKFLOW_CAPTURE=1 uses the real integrated host. */
import { test, expect } from "@playwright/test";
import { WorkflowGallery } from "./captureGallery";
import { captureImports } from "./captureImports";
import { authenticated, guard, keepWords, makePicture, project } from "./helpers";

test("capture the integrated Vidra screen families", async ({ page, browser }) => {
  test.setTimeout(240000);
  const gallery = new WorkflowGallery();
  if (process.env.WORKFLOW_IMPORT_CAPTURE_ONLY === "1") {
    await authenticated(page);
    await page.setViewportSize({ width: 1440, height: 960 });
    await project(page);
    await captureImports(page, browser, gallery);
    await guard(page);
    return;
  }
  await page.route("**/*", async route => { const host = new URL(route.request().url()).hostname; if (["127.0.0.1", "localhost"].includes(host)) await route.continue(); else await route.abort("blockedbyclient"); });
  await page.setViewportSize({ width: 1440, height: 960 });
  for (const [path, name] of [["/", "landing"], ["/product/images", "product-pictures"], ["/product/video", "product-video"], ["/product/editor", "product-editor"], ["/product/sketch", "product-sketch"], ["/docs", "docs-home"], ["/docs/start", "docs-start"], ["/contact", "support"], ["/privacy-policy", "privacy-policy"], ["/terms-of-service", "terms"], ["/signin", "signin"], ["/signup", "signup"], ["/forgot-password", "forgot-password"], ["/reset-password", "reset-link-missing"], ["/email-verification", "verification-signed-out"]] as const) {
    await page.goto(path);
    if (path === "/signin" || path === "/signup") await expect(page.getByRole("button", { name: path === "/signin" ? "Sign in" : "Create account", exact: true })).toBeVisible();
    else await expect(page.getByRole("heading", { level: 1 }).first()).toBeVisible();
    await gallery.capture(page, name, [], "Real public/auth route and local assets; no Firebase provider operation invoked.");
  }
  await authenticated(page);
  await page.route("**/api/projects", async route => { if (route.request().method() === "GET") await route.fulfill({ json: { success: true, data: [] } }); else await route.continue(); });
  await page.goto("/app");
  await expect(page.getByRole("heading", { name: "Start your first project" })).toBeVisible();
  await gallery.capture(page, "projects-empty", ["X12"], "Real routed browser component with an explicitly empty list response at its API boundary, independent of other QA projects.");
  await page.getByRole("searchbox", { name: "Search projects" }).fill("No matching campaign");
  await expect(page.getByRole("heading", { name: "No matching projects" })).toBeVisible();
  await gallery.capture(page, "projects-no-match", ["X14"], "Real search interaction over the controlled empty-list boundary; no project rows are fabricated.");
  await page.unroute("**/api/projects");
  await project(page);
  await keepWords(page, "A stadium under evening light");
  await gallery.capture(page, "request-ready");
  await captureImports(page, browser, gallery);
  await page.getByRole("button", { name: "Model: Flux Schnell" }).click();
  await gallery.capture(page, "model-picker");
  await page.keyboard.press("Escape");
  await page.getByRole("button", { name: "Open projects", exact: true }).click({ button: "right" });
  await gallery.capture(page, "project-menu");
  await page.getByRole("dialog").getByRole("button", { name: "Rename project" }).click();
  await gallery.capture(page, "project-rename");
  await page.getByRole("dialog").getByRole("button", { name: "Cancel", exact: true }).click();
  await page.getByRole("dialog").getByRole("button", { name: "Conversations", exact: true }).click();
  await expect(page.getByRole("main", { name: "Project conversations" })).toBeVisible();
  await gallery.capture(page, "project-conversations", ["P02"]);
  await page.getByRole("button", { name: "First ideas", exact: false }).first().click();
  const label = "A stadium picture made in the browser proof";
  await makePicture(page, label);
  await page.getByRole("button", { name: `View ${label}`, exact: true }).click();
  await expect(page.getByRole("img", { name: label, exact: true })).toBeVisible();
  await gallery.capture(page, "picture-viewer");
  await page.getByRole("button", { name: "Use", exact: true }).click();
  await gallery.capture(page, "picture-use-menu");
  await page.getByRole("button", { name: /Media actions/ }).click();
  await gallery.capture(page, "picture-actions");
  await page.getByRole("button", { name: "Share", exact: true }).click();
  await expect(page.getByRole("dialog").getByRole("button", { name: /Who has access Only you/ })).toBeVisible();
  await gallery.capture(page, "share-private");
  await page.keyboard.press("Escape");
  await page.getByRole("button", { name: "Project media", exact: true }).click();
  await expect(page.getByRole("button", { name: `Open ${label}`, exact: true })).toBeVisible();
  await gallery.capture(page, "media-library", ["M01"]);
  await page.getByRole("searchbox", { name: "Find media" }).fill("No matching file");
  await expect(page.getByRole("heading", { name: "No matching media" })).toBeVisible();
  await gallery.capture(page, "media-no-match", ["X13"]);
  await page.getByRole("button", { name: "Clear search", exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await gallery.capture(page, "media-library-mobile");
  await page.getByRole("button", { name: "Project options", exact: true }).click();
  await gallery.capture(page, "project-menu-mobile", ["B22"]);
  await page.keyboard.press("Escape");
  await page.setViewportSize({ width: 1440, height: 960 });
  await page.getByRole("button", { name: "Video edits", exact: true }).first().click();
  await expect(page.getByRole("main", { name: "Video editor" })).toBeVisible();
  await gallery.capture(page, "video-editor-empty");
  await page.getByRole("button", { name: `Add ${label}`, exact: true }).click();
  await expect(page.getByLabel("Duration seconds", { exact: true })).toBeVisible();
  await gallery.capture(page, "video-editor-picture");
  await page.getByLabel("Duration seconds", { exact: true }).fill("1");
  await page.getByLabel("Duration seconds", { exact: true }).press("Enter");
  await page.getByRole("button", { name: "Export", exact: true }).click();
  await expect(page.getByRole("region", { name: "Export panel" })).toBeVisible();
  await gallery.capture(page, "export-rendering");
  await expect(page.getByRole("button", { name: "Download", exact: true })).toBeEnabled({ timeout: 60000 });
  await gallery.capture(page, "export-ready");
  await page.getByRole("button", { name: "Open Sketch", exact: true }).click();
  await expect(page.getByRole("button", { name: "Start preview", exact: true })).toBeVisible();
  await gallery.capture(page, "sketch-off");
  await page.getByRole("button", { name: "Start preview", exact: true }).click();
  await expect(page.getByRole("img", { name: "Last displayed Sketch picture", exact: true })).toBeVisible();
  await gallery.capture(page, "sketch-live");
  await page.getByRole("button", { name: "Pause", exact: true }).click();
  await gallery.capture(page, "sketch-paused");
  await page.getByRole("button", { name: "Sketch settings", exact: true }).click();
  await gallery.capture(page, "sketch-settings");
  await page.keyboard.press("Escape");
  await page.getByRole("button", { name: "Back to project", exact: true }).click();
  await page.getByRole("button", { name: "Account", exact: true }).click();
  await expect(page.getByRole("button", { name: "Edit name", exact: true })).toBeVisible();
  await gallery.capture(page, "account-profile", ["K01"]);
  for (const [name, key] of [["Security", "K08"], ["Usage", "K11"], ["Data and privacy", "K17"]] as const) { await page.getByRole("link", { name, exact: true }).click(); await expect(page.getByRole("heading", { name, exact: true })).toBeVisible(); if (name === "Usage") await expect(page.getByRole("cell", { name: label, exact: true })).toBeVisible(); await gallery.capture(page, `account-${name.toLowerCase().replaceAll(" ", "-")}`, [key]); }
  await page.getByRole("link", { name: "Profile", exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await gallery.capture(page, "account-profile-mobile", ["N23"]);
  await guard(page);
  await gallery.save();
});
