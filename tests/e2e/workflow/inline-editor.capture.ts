import { test, expect } from "@playwright/test";
import { z } from "zod";
import { VideoEditSchema } from "@shared/schemas/workflow/video-edit.schemas";
import { authenticated, authHeaders, data, guard, keepWords, makePicture, project } from "./helpers";
import { WorkflowGallery } from "./captureGallery";

test("inline editing retains composer, saved timeline and exact selected input while inspecting history", async ({ page }) => {
  test.setTimeout(90000);
  await authenticated(page);
  await page.setViewportSize({ width: 1440, height: 900 });
  const id = await project(page);
  const label = "Picture selected for an inline video edit";
  const versionId = await makePicture(page, label);
  const words = "Continue these unfinished words beside the timeline";
  await keepWords(page, words);
  await page.getByRole("button", { name: `View ${label}`, exact: true }).click();
  const viewer = page.getByRole("region", { name: "Media viewer", exact: true });
  await viewer.getByRole("button", { name: "Use", exact: true }).click();
  await page.getByRole("button", { name: "Add to edit", exact: true }).click();
  await expect.poll(() => new URL(page.url()).searchParams.get("view")).toBe("video-workspace");
  await expect(page.getByLabel("Current request words", { exact: true })).toHaveValue(words);
  await expect(page.getByLabel("Video timeline", { exact: true })).toBeVisible();
  const getEdit = async () => (await data(await page.request.get(`/api/projects/${id}/video-edits`, { headers: authHeaders }), z.array(VideoEditSchema)))[0]!;
  await expect.poll(async () => (await getEdit()).composition.items.filter(item => item.versionId === versionId).length).toBe(1);
  const revision = (await getEdit()).revision;
  const gallery = new WorkflowGallery(`${process.env.WORKFLOW_GALLERY_OUTPUT ?? "output/playwright/integrated-workflow"}/inline-editor`);
  await gallery.capture(page, "inline-editor-timeline-shown");
  await page.getByRole("button", { name: "Timeline", exact: true }).click();
  await page.getByRole("button", { name: "Hide timeline", exact: true }).click();
  await page.keyboard.press("Escape");
  await expect(page.getByLabel("Video timeline", { exact: true })).toHaveCount(0);
  await expect(page.getByLabel("Current request words", { exact: true })).toHaveValue(words);
  await gallery.capture(page, "inline-editor-timeline-hidden");
  expect((await getEdit()).revision).toBe(revision);
  await page.getByRole("button", { name: "Timeline", exact: true }).click();
  await page.getByRole("button", { name: "Show timeline", exact: true }).click();
  await page.keyboard.press("Escape");
  await page.getByRole("button", { name: `View ${label}`, exact: true }).click();
  await expect(page.getByRole("button", { name: "Back to edit", exact: true })).toBeVisible();
  await expect(page.getByLabel("Video timeline", { exact: true })).toBeVisible();
  await expect(page.getByLabel("Current request words", { exact: true })).toHaveValue(words);
  await gallery.capture(page, "inline-editor-inspecting-history");
  await page.getByRole("button", { name: "Back to edit", exact: true }).click();
  await expect(page.getByLabel("Video timeline", { exact: true })).toBeVisible();
  await expect(page.getByLabel("Current request words", { exact: true })).toHaveValue(words);
  await expect(page.getByRole("button", { name: "Back to edit", exact: true })).toHaveCount(0);
  expect((await getEdit()).revision).toBe(revision);
  await gallery.capture(page, "inline-editor-returned");
  await page.reload();
  await expect(page.getByLabel("Video timeline", { exact: true })).toBeVisible();
  expect((await getEdit()).composition.items.filter(item => item.versionId === versionId)).toHaveLength(1);
  await guard(page);
});
