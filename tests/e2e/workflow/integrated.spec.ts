test("project rename and archived conversation recovery preserve the original draft through reopen", async ({ page }) => {
  const id = await project(page);
  const original = (await conversations(page))[0]!;
  await makePicture(page, "An accepted base request before opening another conversation");
  const words = "Unfinished directions remain in their original conversation";
  await keepWords(page, words);
  // Seed a second conversation and an archive through the owned API. P02 has no invented New conversation row.
  const second = await data(await page.request.post(`/api/projects/${id}/conversations`, { headers: authHeaders, data: { id: `conversation_${crypto.randomUUID()}`, name: "Second conversation" } }), ConversationSchema);
  const latestOriginal = (await conversations(page)).find(row => row.id === original.id)!;
  await data(await page.request.patch(`/api/projects/${id}/conversations/${original.id}`, { headers: authHeaders, data: { expectedRevision: latestOriginal.revision, status: "archived" } }), ConversationSchema);
  await page.goto(`/app/project/${id}?conversation=${second.id}`);
  await expect(page.getByLabel("Current request words", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Open projects", exact: true }).click({ button: "right" });
  const options = page.getByRole("dialog");
  await options.getByRole("button", { name: "Rename project", exact: true }).click();
  await options.getByLabel("Project name", { exact: true }).fill("Renamed browser project");
  await options.getByRole("button", { name: "Save changes", exact: true }).click();
  await expect.poll(async () => (await ownedProject(page)).name).toBe("Renamed browser project");
  await options.getByRole("button", { name: "Archived conversations", exact: true }).click();
  const firstRow = options.locator("article").filter({ hasText: original.name });
  await firstRow.getByRole("button", { name: "Rename", exact: true }).click();
  await options.getByLabel("Conversation name", { exact: true }).fill("Retained first conversation");
  await options.getByRole("button", { name: "Save name", exact: true }).click();
  await expect.poll(async () => (await conversations(page)).find(row => row.id === original.id)?.name).toBe("Retained first conversation");
  await options.getByRole("button", { name: "Restore", exact: true }).click();
  await expect.poll(async () => (await conversations(page)).find(row => row.id === original.id)?.status).toBe("active");
  const originalDrafts = await page.request.get(`/api/projects/${id}/conversations/${original.id}/drafts`, { headers: authHeaders });
  expect(await originalDrafts.text()).toContain(words);
  await options.getByRole("button", { name: "Back to project options", exact: true }).click();
  await options.getByRole("button", { name: "Conversations", exact: true }).click();
  await page.getByRole("main", { name: "Project conversations", exact: true }).getByRole("button", { name: /^Retained first conversation/ }).click();
  await expect.poll(async () => new URL(page.url()).searchParams.get("conversation")).toBe(original.id);
  if (await page.getByRole("dialog", { name: "Unfinished requests" }).count()) await page.getByRole("button", { name: words, exact: true }).click();
  await expect(page.getByLabel("Current request words", { exact: true })).toHaveValue(words);
  await page.reload();
  await expect(page.getByLabel("Current request words", { exact: true })).toHaveValue(words);
  await guard(page);
});

test("native project import writes a verified media version and hide/restore/copy retain exact bytes", async ({ page }) => {
  const id = await project(page);
  await keepWords(page, "Keep these request words while importing media");
  await page.getByRole("button", { name: "Project media", exact: true }).click();
  const library = page.getByRole("main", { name: "Project Media library" });
  await library.getByLabel("Choose media file", { exact: true }).setInputFiles("tests/e2e/cross-mode/frame.png");
  await expect(library.getByRole("button", { name: "Open frame.png", exact: true })).toBeVisible();
  const imported = (await versions(page)).find(version => version.label === "frame.png")!;
  expect(imported).toMatchObject({ origin: { kind: "upload" }, object: { identity: "verified" }, metadata: { state: "verified", width: 32, height: 32 } });
  await library.getByRole("button", { name: "More for frame.png", exact: true }).click();
  await page.getByRole("menuitem", { name: "Hide", exact: true }).click();
  await expect.poll(async () => (await versions(page)).find(version => version.id === imported.id)?.hidden).toBe(true);
  await expect(library.getByRole("button", { name: "Open frame.png", exact: true })).toHaveCount(0);
  await library.getByRole("switch", { name: "Show hidden", exact: true }).check();
  await library.getByRole("button", { name: "More for frame.png", exact: true }).click();
  await page.getByRole("menuitem", { name: "Restore", exact: true }).click();
  await expect.poll(async () => (await versions(page)).find(version => version.id === imported.id)?.hidden).toBe(false);
  const targetId = `project_${crypto.randomUUID()}`;
  await data(await page.request.post("/api/projects", { headers: authHeaders, data: { id: targetId, name: "Copy destination" } }), ProjectSchema);
  await library.getByRole("button", { name: "More for frame.png", exact: true }).click();
  await page.getByRole("menuitem", { name: "Copy to project", exact: true }).click();
  await page.getByLabel("Destination project", { exact: true }).selectOption(targetId);
  await page.getByRole("button", { name: "Copy picture", exact: true }).click();
  await expect.poll(async () => (await data(await page.request.get(`/api/projects/${targetId}/media`, { headers: authHeaders }), z.array(MediaVersionSchema))).length).toBe(1);
  const copied = (await data(await page.request.get(`/api/projects/${targetId}/media`, { headers: authHeaders }), z.array(MediaVersionSchema)))[0]!;
  expect(copied.object.identity === "verified" && imported.object.identity === "verified" && copied.object.sha256 === imported.object.sha256).toBe(true);
  await page.reload();
  await expect(library.getByRole("button", { name: "Open frame.png", exact: true })).toBeVisible();
  expect((await drafts(page, id)).some(draft => draft.instructions === "Keep these request words while importing media")).toBe(true);
  await library.getByRole("button", { name: "Open frame.png", exact: true }).click();
  let release: (() => void) | undefined;
  const transfer = new Promise<void>(resolve => { release = resolve; });
  await page.route("**/__test/upload/*", async route => { await transfer; await route.continue(); });
  await page.getByLabel("Choose a project input file", { exact: true }).setInputFiles("tests/e2e/cross-mode/frame-blue.png");
  try {
    await expect(page.locator(".vf-input-picture").getByRole("img", { name: "Uploading", exact: true })).toBeVisible();
    await expect.poll(async () => (await drafts(page, id)).some(draft => draft.inputs.some(input => input.state === "importing"))).toBe(true);
  } finally { release?.(); }
  await expect.poll(async () => (await versions(page, id)).some(version => version.label === "frame-blue.png")).toBe(true);
  await expect(page.locator(".vf-import-panel")).toHaveCount(0);
  await expect(page.locator(".vf-input-picture[data-unavailable]")).toHaveCount(0);
  await expect.poll(async () => page.locator(".vf-input-picture > img").evaluate(image => image instanceof HTMLImageElement && image.complete && image.naturalWidth > 0)).toBe(true);
  await page.unroute("**/__test/upload/*");
  await page.reload();
  await expect(page.getByLabel("Current request words", { exact: true })).toHaveValue("Keep these request words while importing media");
  await expect(page.locator(".vf-input-picture[data-unavailable]")).toHaveCount(0);
  await expect.poll(async () => page.locator(".vf-input-picture > img").evaluate(image => image instanceof HTMLImageElement && image.complete && image.naturalWidth > 0)).toBe(true);
  await guard(page);
});

